export function timingLabel(offset) {
  if (offset >= 0) {
    if (offset >= 28) return `결혼 후 ${Math.round(offset / 30)}개월`
    if (offset >= 7) return `결혼 후 ${Math.round(offset / 7)}주`
    return `결혼 후 ${offset}일`
  }
  const d = -offset
  if (d >= 60) return `${Math.round(d / 30)}개월 전`
  if (d >= 14) return `${Math.round(d / 7)}주 전`
  return `${d}일 전`
}

export function recommendedPct(budget) {
  if (budget < 3000) return [55, 15, 12, 18]
  if (budget <= 7000) return [60, 20, 10, 10]
  return [55, 22, 11, 12]
}
