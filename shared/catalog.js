export const STATUS = ['예정', '진행 중', '완료']

export function timingLabel(offset) {
  if (offset >= 0) {
    if (offset >= 28) return `결혼 후 ${Math.round(offset / 30)}개월`
    if (offset >= 7) return `결혼 후 ${Math.round(offset / 7)}주`
    return `결혼 후 ${offset}일`
  }
  const d = -offset
  if (d >= 60) return `${Math.round(d / 30)}개월 전`
  if (d >= 14) return `${Math.round(d / 7)}주 전`
  return `${d}일 전`
}

export function recommendedPct(budget) {
  if (budget < 3000) return [55, 15, 12, 18]
  if (budget <= 7000) return [60, 20, 10, 10]
  return [55, 22, 11, 12]
}

// 기본 항목 + 우리 플래너의 수정 사항 + 직접 추가한 항목을 합친 목록
export function mergeTasks(states = [], custom = []) {
  const st = Object.fromEntries(states.map((s) => [s.key, s]))
  const base = TASKS.map((d) => {
    const s = st[d.key]
    return { ...d, custom: false, hidden: !!s?.hidden, name: s?.name || d.name, offset: s?.offset_days ?? d.offset, subs: s?.sub_names || d.subs }
  })
  const mine = custom.map((c) => ({
    key: c.key, phase: c.phase, axis: c.axis, name: c.name, offset: c.offset_days, cat: c.cat || null,
    desc: '', subs: c.sub_names || [], tip: '', why: '', custom: true, hidden: !!st[c.key]?.hidden,
  }))
  return [...base, ...mine].sort((a, b) => a.offset - b.offset)
}
